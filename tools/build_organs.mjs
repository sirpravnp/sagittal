// Bundles organs/index.json, organs/manifests/*.json and organs/references.json into
// organs/organs.js, a classic script (no fetch/modules) so figures work from file://.
import { readFileSync, writeFileSync } from 'node:fs';

const read = (p) => JSON.parse(readFileSync(new URL('../organs/' + p, import.meta.url), 'utf8'));
const index = read('index.json');
const manifests = {};
for (const { id } of index) manifests[id] = read(`manifests/${id}.json`);
const references = read('references.json');

const out = '// GENERATED by tools/build_organs.mjs (npm run organs). Do not edit.\n'
  + 'window.SagittalOrgans = ' + JSON.stringify({ index, manifests, references }) + ';\n';
writeFileSync(new URL('../organs/organs.js', import.meta.url), out);
